/**
 * 秘書へ渡す systemInstruction の全体を組み立てる。節をこの順につなぐ。
 *
 * ATTENTION: 節の順番は、後ろに行くほど話す直前の文脈から遠くなる。読み方のような、話し始めに効かせたい
 * 指示は、ここだけに頼らず最初のターンにも入れること（formatUserNamePronunciation 参照）。
 *
 * @param {object} params
 * @param {string} params.todayFull 今日の日付（例: 2026年9月20日土曜日）
 * @param {string} params.nowTimeStr 今の時刻（HH:mm）
 * @param {string} params.secretaryName 秘書の名前
 * @param {string} params.basePrompt 秘書の人物の設定（設定が空なら既定の文）
 * @param {string} params.userName リスナーの呼び方
 * @param {Record<string, any>} params.listenerProfile リスナーの情報（config.show.user_profile）
 * @param {Array<any>} params.ttsDict 発声辞書（tts_dict.json）
 * @param {string} params.consultableAgentNames 相談できるエージェントの名前（・区切り）
 * @param {boolean} params.obsidianEnabled Obsidian 連携が有効か
 * @returns {string} systemInstruction の全文
 */
function buildSystemInstructionText({
  todayFull, nowTimeStr, secretaryName, basePrompt, userName,
  listenerProfile, ttsDict, consultableAgentNames, obsidianEnabled,
}) {
  return buildIdentitySection({ todayFull, nowTimeStr, secretaryName, basePrompt, userName })
    // 短い呼び方が設定されているときは、フルネームを話す場面が無いので読み方の指示も要らない
    + (listenerProfile.short_name ? '' : formatUserNamePronunciation(listenerProfile.name, listenerProfile.name_reading))
    + formatListenerProfile(listenerProfile)
    + formatTtsDictForPrompt(ttsDict)
    + buildPronunciationGuidanceSection()
    + buildVocalToneStabilitySection()
    // 会話をまたいで覚えている学習（secretary-memory.js）
    + secretaryMemory.formatLearningsForPrompt()
    // 秘書自身の日記から作ったふり返り（放送のエージェントと同じ仕組み）
    + buildSelfReflectionSection()
    // 直近の放送の内容（同じ放送局の一員として、番組を把握しておくため）
    + buildBroadcastAwarenessSection()
    // リスナーが実際に見た YouTube（今どんな関心を持っているか）
    + buildWatchedVideosSection()
    // 秘書のループ（secretary-loop.js）が、接続と接続の間に見つけた変化（新着のメール・近い予定・
    // 気象の警報・速報・相場の急な動き）。取り出すと同時に消えるので、次の接続で繰り返されない
    + secretaryLoop.consumePendingNotificationsForPrompt()
    + buildBehaviorRulesSection()
    + buildFeatureListAndWaitRuleSection()
    + buildFreshDataRuleSection()
    + buildNewsPersonalizationSection(listenerProfile)
    + buildSelfIntroductionSection({ consultableAgentNames, obsidianEnabled })
    + buildObsidianUsageSection(obsidianEnabled)
    + buildAgentNameJudgmentSection()
    + buildCanvasHygieneSection()
    + buildSelfQuestionHygieneSection();
}

module.exports = { buildSystemInstructionText };
