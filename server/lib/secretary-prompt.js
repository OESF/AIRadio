    + `実際には何も実行していません。画面に表示すると言ったら、その直後に必ず実際の`
    + `キャンバス表示機能を呼び出してください。呼び出した後は、その内容（太字や箇条書きの`
    + `詳細）を声に出して読み上げる必要はありません。画面に表示したことだけを短く伝えてください。`
