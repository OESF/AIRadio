// 起動時に渡す直近の放送の件数と、1発言あたりの文字数。プロンプト全体を膨らませない範囲に絞る。
// もっと前まで見たいときは、放送内容を読む機能で取りに行かせる
const BROADCAST_AWARENESS_COUNT = 12;
const BROADCAST_AWARENESS_TEXT_LEN = 90;

/**
 * 直近の放送で実際に流れた発言を入れる（同じ放送局の一員として、聞かれる前から知っている状態にするため）。
 *
 * 放送は各チャンネルの WebSocket で進み、秘書はそれとは別の接続なので、渡さないと番組の中身を何も知らない。
 * 発言は conversation_history.jsonl に残っているので、そこから読む（secretary-tools-history.js）。
 *
 * @returns {string} プロンプトに入れる文（記録が無ければ空文字）
 */
function buildBroadcastAwarenessSection() {
  let entries = [];
  try {
    entries = historyTools.readBroadcastHistory({ channel: 'all', count: BROADCAST_AWARENESS_COUNT });
  } catch { return ''; }
  if (entries.length === 0) return '';
  const lines = historyTools.formatBroadcastLines(entries, BROADCAST_AWARENESS_TEXT_LEN);
  return `\n\n【直近の放送で流れた内容】あなたはこのAI Radioの中にいる秘書で、リスナーが`
    + `聴いている番組と同じ放送局の一員です。直前までに実際に流れた発言は次のとおりです。\n${lines}\n`
    + `※ これは放送に出ている人たち（キャスター・アシスタント・各センターの担当者・`
    + `パーソナリティ）の発言であって、あなた自身の発言ではありません。あなたが言ったことの`
    + `ように話さないでください。また、聞かれてもいないのにこの一覧を読み上げる必要は`
    + `ありません。リスナーが番組の話題に触れたときに、自然に踏まえて応じてください。`
    + `ここに無い、もっと前の放送について尋ねられた場合は、放送内容を読む機能で確認してから`
    + `答えてください（記憶や推測で番組の内容を作って話すことは絶対にしないでください）。`;
}

